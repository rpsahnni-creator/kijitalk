function buildVocabLessons(t: VocabTheme, baseOrder: number): LessonSeed[] {
  const vocabulary = t.words.map((w) => w[0]);
  const used = vocabulary;

  const lesson1 = {
    title: `${t.title} — Recognize`,
    description: `Learn to recognize key words for ${t.title.toLowerCase()}.`,
    level: t.level,
    category: t.category,
    durationMinutes: 8,
    order: baseOrder,
    tags: ['vocabulary', t.key],
    gradeBand: t.gradeBand,
    content: {
      vocabulary,
      phrases: t.phrases,
      exercises: [
        mcqEx(
          `Which word means "${t.words[0][1]}"?`,
          t.words[0][0],
          pickRandom(DISTRACTOR_WORDS, 3, used)
        ),
        mcqEx(
          `Which word means "${t.words[1][1]}"?`,
          t.words[1][0],
          pickRandom(DISTRACTOR_WORDS, 3, used)
        ),
        matchEx(
          t.words.slice(2, 6).map(([en, hi]) => ({ left: en, right: hi })),
          'Match the English word to its Hindi meaning:'
        ),
      ],
    },
  };

  const lesson2 = {
    title: `${t.title} — Use in a Sentence`,
    description: `Practice using ${t.title.toLowerCase()} vocabulary in real sentences.`,
    level: t.level,
    category: t.category,
    durationMinutes: 10,
    order: baseOrder + 1,
    tags: ['vocabulary', t.key],
    gradeBand: t.gradeBand,
    content: {
      vocabulary,
      phrases: t.phrases,
      exercises: [
        fillBlankEx(t.words[0][2], t.words[0][0]),
        fillBlankEx(t.words[2][2], t.words[2][0]),
        fillBlankEx(t.words[4][2], t.words[4][0]),
        wordBankEx(t.phrases[0]),
      ],
    },
  };

  const lesson3 = {
    title: `${t.title} — Review`,
    description: `Mixed review of ${t.title.toLowerCase()} vocabulary.`,
    level: t.level,
    category: t.category,
    durationMinutes: 10,
    order: baseOrder + 2,
    tags: ['vocabulary', t.key],
    gradeBand: t.gradeBand,
    content: {
      vocabulary,
      phrases: t.phrases,
      exercises: [
        translateEx(t.words[6] ? t.words[6][1] : t.words[0][1], t.words[6] ? t.words[6][0] : t.words[0][0]),
        mcqEx(
          `Which word means "${(t.words[7] ?? t.words[1])[1]}"?`,
          (t.words[7] ?? t.words[1])[0],
          pickRandom(DISTRACTOR_WORDS, 3, used)
        ),
        repeatEx(t.phrases[1] ?? t.phrases[0]),
        wordBankEx(t.phrases[2] ?? t.phrases[0]),
      ],
    },
  };

  return [lesson1, lesson2, lesson3];
}

export const VOCABULARY_LESSONS: LessonSeed[] = THEMES.flatMap((t, i) => buildVocabLessons(t, 1000 + i * 4));
